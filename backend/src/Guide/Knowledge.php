    /** Words that contain a topic key but mean something else. */
    private const NOT_TOPIC = ['กราฟ' => ['กราฟิก'], 'คิว' => ['คิวอาร์', 'คิวซี'], 'ทรี' => ['ทรีทเมนต์']];

    /** Knowledge-base key matching a unit topic/name (e.g. "การใช้งานสแตก" -> "สแตก"), or null. */
    public static function topicKey(string ...$names): ?string
    {
        foreach ($names as $name) {
            $name = trim($name);
            if ($name === '') {
                continue;
            }
            foreach (array_keys(self::TOPICS) as $key) {
                // Thai has no spaces: "กราฟิก" contains "กราฟ", "คิวอาร์โค้ด" contains "คิว"
                $other = str_replace(self::NOT_TOPIC[$key] ?? [], '', $name);
                if (mb_strpos($other, $key) !== false || mb_strpos($key, $name) !== false) {
                    return $key;
                }
            }
        }
        return null;
    }

